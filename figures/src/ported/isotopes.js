/** The weighted average of the peaks' masses ({ mass, abundance }), or null with no abundance at all. */
export function isAverage(peaks) {
  const total = peaks.reduce((s, p) => s + p.abundance, 0);
  return total > 0 ? peaks.reduce((s, p) => s + p.mass * p.abundance, 0) / total : null;
}
/** The peaks' heights: their abundances in %, or against the tallest as 100. */
export function isHeights(peaks, scale) {
  const tallest = Math.max(...peaks.map(p => p.abundance));
  return peaks.map(p => (scale === 'percent' || !tallest ? p.abundance : (p.abundance / tallest) * 100));
}
/** An abundance over its peak: two decimal places, or three significant figures below 0.1 (0.0115), and 100 as 100. */
export function isAbundanceText(v) {
  if (v === 100) return '100';
  if (v > 0 && v < 0.1) return String(Number(v.toPrecision(3)));
  return v.toFixed(2);
}
