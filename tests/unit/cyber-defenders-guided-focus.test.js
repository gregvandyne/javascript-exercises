  let total = 0;
  for (const { band, n, deck: d } of allDecks()) {
    d.slides.forEach((s, si) => { if (s.img && Array.isArray(s.focus)) s.focus.forEach((f, fi) => { total++; assert.ok(seen.has(`${band}/${n}/${si}/${fi}`), `${band}/${n} s${si} step ${fi + 1} in registry`); }); });
  }
