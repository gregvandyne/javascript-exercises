// Build the Builder's CANVAS RULES (server/builder/canvas-rules.js) from docs/canvas-api.md: the page's section marked
// <!-- builder:rules --> ... <!-- /builder -->, as it is (it is written as plain lines for the model), plus the kit's
// own tool list (canvas/src/logic.js), so a tool the model may name is always one the kit has. The result is fixed text
// (no dates, no hashes): prompt.js sends it only for canvas builds, so the arcade prompt is untouched.
// tests/unit/builder-canvas.test.js fails when the file is out of date.
//   node scripts/build-canvas-rules.js           write server/builder/canvas-rules.js
//   node scripts/build-canvas-rules.js --check   exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { TOOL_IDS } from '../canvas/src/logic.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'server/builder/canvas-rules.js');

export function rulesText() {
  const md = fs.readFileSync(path.join(ROOT, 'docs/canvas-api.md'), 'utf8');
  const m = /<!-- builder:rules -->\n([\s\S]*?)\n<!-- \/builder -->/.exec(md);
  if (!m) throw new Error('docs/canvas-api.md has no <!-- builder:rules --> section');
  return `${m[1].trim()}\n- The kit's tools (no others): ${TOOL_IDS.join(', ')}.`;
}
export const fileText = () => `// Generated by scripts/build-canvas-rules.js from docs/canvas-api.md (its builder:rules section) and the kit's tool
// list (canvas/src/logic.js). Do not edit: change the page and run \`node scripts/build-canvas-rules.js\`.
// tests/unit/builder-canvas.test.js checks it.
export const CANVAS_RULES_SOURCE = ${JSON.stringify(rulesText())};
`;

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const text = fileText();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.error('server/builder/canvas-rules.js is out of date: run node scripts/build-canvas-rules.js'); process.exit(1); }
    console.log('canvas-rules.js is up to date');
  } else { fs.writeFileSync(OUT, text); console.log(`wrote ${path.relative(ROOT, OUT)}`); }
}
