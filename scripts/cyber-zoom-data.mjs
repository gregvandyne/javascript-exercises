#!/usr/bin/env node
// Zoom-to-cue data for the course engine (public/js/course-zoom.js), from the captures' recorded text
// (scripts/cyber-shots-rects.json: '~bodyFont' and '~words', written by scripts/cyber-shots.js):
// (and CS Quest's own captures, scripts/csq-shots-rects.json, written by the same tool with --course csq):
//   public/js/course-zoom-data.js   { picture key: the game's body text size in px of the 1280-wide master }
//   public/img/zoom/<key>.json      the picture's word boxes, [x, y, w, h] in % of the picture
//
//   node scripts/cyber-zoom-data.mjs          writes them
//   node scripts/cyber-zoom-data.mjs --check  exits 1 when they are out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const INDEX = path.join(ROOT, 'public', 'js', 'course-zoom-data.js');
const DIR = path.join(ROOT, 'public', 'img', 'zoom');

/** -> Map(file path -> contents) of everything this script writes. */
export function build() {
  const read = f => (fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : {});
  const rects = Object.assign(read(path.join(ROOT, 'scripts', 'cyber-shots-rects.json')), read(path.join(ROOT, 'scripts', 'csq-shots-rects.json')));
  const index = {}, files = new Map();
  for (const key of Object.keys(rects).sort()) {
    const r = rects[key];
    if (typeof r['~bodyFont'] !== 'number' || !Array.isArray(r['~words'])) continue;
    index[key] = r['~bodyFont'];
    files.set(path.join(DIR, `${key}.json`), JSON.stringify(r['~words']) + '\n');
  }
  files.set(INDEX, '// Generated by scripts/cyber-zoom-data.mjs from scripts/cyber-shots-rects.json and csq-shots-rects.json: do not edit.\n'
    + '// { picture key: the game\'s body text size, px of the 1280-wide capture }; word boxes: /img/zoom/<key>.json\n'
    + `export default ${JSON.stringify(index)};\n`);
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const files = build();
  if (process.argv.includes('--check')) {
    const stale = [...files].filter(([f, js]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== js);
    if (stale.length) { console.error(`zoom data out of date (${stale.length} files): node scripts/cyber-zoom-data.mjs`); process.exit(1); }
    console.log(`zoom data: ${files.size - 1} pictures, up to date`);
  } else {
    fs.rmSync(DIR, { recursive: true, force: true });
    for (const [f, js] of files) { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, js); }
    console.log(`wrote ${files.size - 1} word files and public/js/course-zoom-data.js`);
  }
}
