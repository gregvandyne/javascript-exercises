// Build the Builder's 2D art catalogue (server/builder/art2d-catalog.js) from what has shipped:
//   - kit2/ART2D.json: which Oomba2D and pack versions exist (only locked versions are in the catalogue);
//   - public/vendor/art2d/<pack>/<version>/pack.json: each world's sprites (with their kind and size in game cells) and
//     the heroes and animals with their names, exactly as Oomba2D reads them.
// The Builder offers the NEWEST locked version of each pack. The result is fixed text (no dates, no hashes): the same
// manifests give the same bytes. Nothing here is typed by hand: a 2D world, hero, animal or sprite name the Builder
// may use is a name a locked manifest has. tests/unit/art2d.test.js fails when the file is out of date.
//   node scripts/build-art2d-rules.js           write server/builder/art2d-catalog.js
//   node scripts/build-art2d-rules.js --check   exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'server/builder/art2d-catalog.js');
const DIR = path.join(ROOT, 'public/vendor/art2d');
const cmp = (a, b) => { const x = a.split('.').map(Number), y = b.split('.').map(Number); for (let i = 0; i < 3; i++) if ((x[i] || 0) !== (y[i] || 0)) return (x[i] || 0) - (y[i] || 0); return 0; };

export function buildCatalog() {
  const lock = JSON.parse(fs.readFileSync(path.join(ROOT, 'kit2/ART2D.json'), 'utf8'));
  const newest = {};
  for (const key of Object.keys(lock.packs)) { const [id, v] = key.split('/'); if (!newest[id] || cmp(newest[id], v) < 0) newest[id] = v; }
  const read = id => JSON.parse(fs.readFileSync(path.join(DIR, id, newest[id], 'pack.json'), 'utf8'));
  const worlds = [], characters = [];
  for (const id of Object.keys(newest)) {
    const m = read(id);
    if (m.kind === 'world') worlds.push({ id: m.id, version: m.version, name: m.name, heroes: m.heroes,
      sprites: Object.entries(m.sprites).map(([name, s]) => ({ name, kind: s.kind, size: s.size })) });
    else for (const [cid, s] of Object.entries(m.sprites)) characters.push({ id: cid, name: s.name, kind: s.kind, pack: m.id, ...(s.group ? { group: s.group } : {}), frames: { idle: s.anims.idle.length, run: s.anims.run.length, jump: s.anims.jump.length } });
  }
  return { helper: Object.keys(lock.helper).sort(cmp).pop(), packs: newest, worlds, characters };
}

export const fileText = (cat = buildCatalog()) => `// Generated by scripts/build-art2d-rules.js from kit2/ART2D.json and the locked 2D art manifests
// (public/vendor/art2d/<pack>/<version>/pack.json). Do not edit: ship a pack version and run
// \`node scripts/build-art2d-rules.js\`. tests/unit/art2d.test.js checks it.
// ART2D_WORLDS: the newest version of every 2D world with every sprite a game may name (size in game cells).
// ART2D_CHARACTERS: every hero and animal that has a sprite sheet (idle, run and jump frames).
export const ART2D_HELPER = ${JSON.stringify(cat.helper)};
export const ART2D_VERSIONS = ${JSON.stringify(cat.packs)};
export const ART2D_WORLDS = ${JSON.stringify(cat.worlds, null, 1)};
export const ART2D_CHARACTERS = ${JSON.stringify(cat.characters, null, 1)};
`;

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const text = fileText();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.error('server/builder/art2d-catalog.js is out of date: run node scripts/build-art2d-rules.js'); process.exit(1); }
    console.log('art2d-catalog.js is up to date');
  } else {
    fs.writeFileSync(OUT, text);
    const c = buildCatalog();
    console.log(`wrote ${path.relative(ROOT, OUT)}: ${c.worlds.length} worlds, ${c.characters.length} heroes and animals`);
  }
}
