// Build the Builder's FIGURE RULES (server/builder/figure-rules.js) from docs/figures-api.md: the page's section marked
// <!-- builder:rules --> ... <!-- /builder -->, as it is, plus the kinds Oomba Figures really has (figures/src), so a
// kind the model may name is always one it can draw. Fixed text (no dates, no hashes): prompt.js adds the pinned tags
// and sends it only for figure builds (builder/figures.js), so the arcade prompt is untouched.
// tests/unit/builder-figures.test.js fails when the file is out of date.
//   node scripts/build-figure-rules.js           write server/builder/figure-rules.js
//   node scripts/build-figure-rules.js --check   exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import '../figures/src/index.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'server/builder/figure-rules.js');

export function rulesText() {
  const md = fs.readFileSync(path.join(ROOT, 'docs/figures-api.md'), 'utf8');
  const m = /<!-- builder:rules -->\n([\s\S]*?)\n<!-- \/builder -->/.exec(md);
  if (!m) throw new Error('docs/figures-api.md has no <!-- builder:rules --> section');
  const OF = globalThis.OombaFigures, by = p => OF.kinds.filter(k => OF.packOf(k) === p);
  return `${m[1].trim()}\n- The kinds (no others), by the Oomba Figures pack each needs (its tag goes right after the Oomba Figures tag): ${['core', ...OF.packs.filter(p => p !== 'core')].map(p => `${p === 'core' ? 'no pack (the core)' : `the ${p} pack`}: ${by(p).join(', ')}`).join('; ')}.`;
}
export const fileText = () => `// Generated by scripts/build-figure-rules.js from docs/figures-api.md (its builder:rules section) and Oomba Figures'
// list of kinds (figures/src). Do not edit: change the page and run \`node scripts/build-figure-rules.js\`.
// tests/unit/builder-figures.test.js checks it.
export const FIGURE_RULES_SOURCE = ${JSON.stringify(rulesText())};
`;

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const text = fileText();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.error('server/builder/figure-rules.js is out of date: run node scripts/build-figure-rules.js'); process.exit(1); }
    console.log('figure-rules.js is up to date');
  } else { fs.writeFileSync(OUT, text); console.log(`wrote ${path.relative(ROOT, OUT)}`); }
}
