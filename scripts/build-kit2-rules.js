// Build the Builder's Kit 2 catalogue (server/builder/kit2-catalog.js) from what has shipped:
//   - kit2/SHIPPED.json: which theme versions exist (a version is in the catalogue only when its theme.json is locked);
//   - public/vendor/themes/<theme>/<version>/theme.json: each world's name, heroes, creatures, pieces (with their sizes,
//     tags and notes), sounds and moves, exactly as Oomba3D reads them;
//   - docs/kit2-api.md: the Oomba3D reference, from `start(options)` on (the page a model reads before writing a Kit 2
//     game), compacted.
// The Builder offers the NEWEST shipped version of each world for new games (a saved game keeps the version it names:
// older versions stay in KIT2_VERSIONS and on disk, unchanged). The result is fixed text (no dates, no hashes): the
// same manifests and docs give the same bytes, so the Builder's Kit 2 block stays cacheable. Nothing here is typed by
// hand: an asset name the Builder may use is a name a shipped manifest has. tests/unit/builder-kit2.test.js fails when
// the file is out of date.
//   node scripts/build-kit2-rules.js           write server/builder/kit2-catalog.js
//   node scripts/build-kit2-rules.js --check   exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'server/builder/kit2-catalog.js');
const THEMES_DIR = path.join(ROOT, 'public/vendor/themes');

const cmp = (a, b) => { const x = a.split('.').map(Number), y = b.split('.').map(Number); for (let i = 0; i < 3; i++) if ((x[i] || 0) !== (y[i] || 0)) return (x[i] || 0) - (y[i] || 0); return 0; };
const round = n => Math.round(n * 10) / 10;

/** { theme: [versions, oldest first] } from kit2/SHIPPED.json (the lock is the list of what shipped). */
export function shippedVersions() {
  const lock = JSON.parse(fs.readFileSync(path.join(ROOT, 'kit2/SHIPPED.json'), 'utf8'));
  const out = {};
  for (const tv of Object.keys(lock.themes || {})) { const [t, v] = tv.split('/'); (out[t] = out[t] || []).push(v); }
  for (const t of Object.keys(out)) out[t].sort(cmp);
  return out;
}

/** One world's catalogue entry from its theme.json (only what a game may name). */
export function worldEntry(theme, version) {
  const m = JSON.parse(fs.readFileSync(path.join(THEMES_DIR, theme, version, 'theme.json'), 'utf8'));
  const who = h => ({ id: h.id, name: h.name });
  return {
    id: m.id, version: m.version, name: m.name, description: m.description, goodFor: m.goodFor || [], engine: m.engine,
    heroes: (m.heroes || []).map(who),
    // Animals a theme ships (Oomba3D 1.2.0 g.creature): what kind it is, how big (width, height, length), the moves its
    // own file has (a pig has no walk: the Builder must never ask one to) and whether it can be the hero.
    creatures: (m.creatures || []).map(c => ({ ...who(c), kind: c.kind || 'land', size: (c.size || []).map(round), moves: c.moves || [], playable: !!c.playable })),
    pieces: (m.pieces || []).map(p => ({ id: p.id, kind: p.kind, size: (p.size || []).map(round), tags: p.tags || [], ...(p.note ? { note: p.note } : {}) })),
    sounds: (m.sounds || []).map(s => s.id),
    moves: Object.keys((m.moves && m.moves.clips) || {}),
  };
}

/** The worlds the Builder offers: the newest shipped version of each theme, in the order they shipped. */
export function buildCatalog() {
  const versions = shippedVersions();
  return { versions, worlds: Object.keys(versions).map(t => worldEntry(t, versions[t][versions[t].length - 1])) };
}

/** docs/kit2-api.md from `start(options)` on, as compact plain text (tables as lines, no emphasis). */
export function buildApi() {
  const md = fs.readFileSync(path.join(ROOT, 'docs/kit2-api.md'), 'utf8');
  const at = md.indexOf('## `start(options)`');
  if (at < 0) throw new Error('docs/kit2-api.md has no "## `start(options)`" section');
  const lines = [];
  for (const raw of md.slice(at).split('\n')) {
    const line = raw.replace(/\*\*/g, '');
    if (/^\|[-| ]+\|$/.test(line.trim())) continue;
    if (/^\|/.test(line.trim())) { lines.push(line.trim().replace(/^\||\|$/g, '').split('|').map(c => c.trim()).join(' · ')); continue; }
    lines.push(line.replace(/^#{2,3} /, '# '));
  }
  return lines.join('\n').replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim();
}

export const fileText = (cat = buildCatalog(), api = buildApi()) => `// Generated by scripts/build-kit2-rules.js from kit2/SHIPPED.json, the shipped theme manifests
// (public/vendor/themes/<theme>/<version>/theme.json) and docs/kit2-api.md. Do not edit: ship a theme version (or change
// the page) and run \`node scripts/build-kit2-rules.js\`. tests/unit/builder-kit2.test.js checks it.
// KIT2_WORLDS: the newest shipped version of every world, with every hero, creature, piece, sound and move a game may
// name. KIT2_VERSIONS: every shipped version of each world (saved games keep theirs). KIT2_API_SOURCE: the Oomba3D
// reference the Builder reads.
export const KIT2_VERSIONS = ${JSON.stringify(cat.versions)};
export const KIT2_WORLDS = ${JSON.stringify(cat.worlds, null, 1)};
export const KIT2_API_SOURCE = ${JSON.stringify(api)};
`;

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const text = fileText();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.error('server/builder/kit2-catalog.js is out of date: run node scripts/build-kit2-rules.js'); process.exit(1); }
    console.log('kit2-catalog.js is up to date');
  } else {
    fs.writeFileSync(OUT, text);
    const c = buildCatalog();
    console.log(`wrote ${path.relative(ROOT, OUT)}: ${c.worlds.length} worlds, ${c.worlds.reduce((n, w) => n + w.pieces.length, 0)} pieces, ${text.length} characters`);
  }
}
