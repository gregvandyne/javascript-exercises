/** The 18 manipulatives' drawn icons (public/icons/tools/<slug>.svg; soft 3D, ours). */
export const TOOL_ICONS = ['rekenreks', 'two-color-counters', 'linking-cubes', 'color-tiles', 'hundred-board', 'base-ten-blocks', 'place-value-disks', 'number-rods',
  'fraction-circles', 'fraction-tiles', 'number-lines', 'bar-models', 'money', 'algebra-tiles', 'xy-coordinate-board', 'geoboard', 'pattern-blocks', 'clock'];
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const entry = e => FLUENT[e] || FLUENT[String(e || '').replace(/\uFE0F/g, '')] || FLUENT[`${String(e || '')}\uFE0F`] || null;
/** Is there an icon for this emoji? */
export const hasIcon = e => !!entry(e);
/** Is this emoji drawn as an Oomba icon below 40 px? -> the Oomba icon's name, else null. */
export const oombaIcon = e => { const x = entry(e); return (x && OOMBA[x[0]]) || null; };
/**
 * An icon as HTML. size (CSS px): below 40 the Oomba icon, an inline <svg> that draws public/icons/oomba/<name>.svg (its
 * ink follows the text color); 40 and up the Fluent 3D picture (WebP, 1x and 2x). An emoji with no Oomba icon, or no 3D
 * picture at 40 and up, draws as before: 3D at 28 px and up, Flat below. data-fx names the Fluent picture it stands for.
 * label: what it says when it stands alone (else decorative: alt="" or aria-hidden). lazy: below the fold (pictures).
 * cls: extra classes. An emoji with no icon comes back as the emoji itself (escaped).
 */
export function iconHtml(e, { size = 20, label = '', lazy = false, cls = '' } = {}) {
  const x = entry(e); if (!x) return esc(e);
  const [name, has3d] = x, oo = OOMBA[name];
  if (oo && !(size >= 40 && has3d)) {
    return `<svg class="fx fx-oo${cls ? ` ${esc(cls)}` : ''}" data-fx="${name}" viewBox="0 0 24 24" width="${size}" height="${size}"${label ? ` role="img" aria-label="${esc(label)}"` : ' aria-hidden="true"'} focusable="false"><use href="/icons/oomba/${oo}.svg?v=${OOMBA_V}#i"/></svg>`;
  }
  const big = size >= 28 && has3d;
  const src = big ? `/icons/fluent/3d/${name}-64.webp` : `/icons/fluent/flat/${name}.svg`;
  return `<img class="fx ${big ? 'fx-3d' : 'fx-flat'}${cls ? ` ${esc(cls)}` : ''}" src="${src}"${big ? ` srcset="/icons/fluent/3d/${name}-64.webp 1x, /icons/fluent/3d/${name}-128.webp 2x"` : ''} width="${size}" height="${size}" alt="${esc(label)}"${label ? '' : ' aria-hidden="true"'}${lazy ? ' loading="lazy"' : ''} decoding="async">`;
}
/** Three tools use Fluent's own 3D picture (abacus, mantelpiece clock, coin): WebP like the other 3D icons. */
const TOOL_FLUENT = new Set(['rekenreks', 'clock', 'money']);
/** A manipulatives tool's icon (decorative: the tool's name is next to it). */
export function toolIconHtml(slug, { size = 40, lazy = false } = {}) {
  if (!TOOL_ICONS.includes(slug)) return '';
  const src = TOOL_FLUENT.has(slug) ? `/icons/tools/${slug}-64.webp" srcset="/icons/tools/${slug}-64.webp 1x, /icons/tools/${slug}-128.webp 2x` : `/icons/tools/${slug}.svg`;
  return `<img class="fx fx-3d fx-tool" src="${src}" width="${size}" height="${size}" alt="" aria-hidden="true"${lazy ? ' loading="lazy"' : ''} decoding="async">`;
}
/** A line that starts with an icon's emoji ("✅ Saved") as [emoji, the words after it], else null. */
export function leadIcon(text) {
  const m = /^(\p{Extended_Pictographic}(?:️|‍\p{Extended_Pictographic}️?)*|[✓✔✖]️?)[  ]+/u.exec(String(text ?? ''));
  return m && hasIcon(m[1]) ? [m[1], String(text).slice(m[0].length)] : null;
}
/** HTML for a line of text whose leading emoji, when it has an icon, is drawn as that icon (the words escaped). */
export const iconLine = (text, size = 18) => { const l = leadIcon(text); return l ? `${iconHtml(l[0], { size })} ${esc(l[1])}` : esc(text); };
/** In the page: el shows the icon for an emoji (decorative), or the emoji itself when there is none. */
export function setIcon(el, e, size = 18) { if (hasIcon(e)) el.innerHTML = iconHtml(e, { size }); else el.textContent = e ?? ''; return el; }
/** In the page: el shows a label, its leading emoji ("🎲 Roll") drawn as the icon; other labels stay plain text. */
export function setLabel(el, text, size = 18) { if (leadIcon(text)) el.innerHTML = iconLine(text, size); else el.textContent = text ?? ''; return el; }
