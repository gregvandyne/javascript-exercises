/** The 18 manipulatives' drawn icons (public/icons/tools/<slug>.svg; soft 3D, ours). */
export const TOOL_ICONS = ['rekenreks', 'two-color-counters', 'linking-cubes', 'color-tiles', 'hundred-board', 'base-ten-blocks', 'place-value-disks', 'number-rods',
  'fraction-circles', 'fraction-tiles', 'number-lines', 'bar-models', 'money', 'algebra-tiles', 'xy-coordinate-board', 'geoboard', 'pattern-blocks', 'clock'];
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const entry = e => FLUENT[e] || FLUENT[String(e || '').replace(/\uFE0F/g, '')] || FLUENT[`${String(e || '')}\uFE0F`] || null;
/** Is there an icon for this emoji? */
export const hasIcon = e => !!entry(e);
/**
 * An icon as HTML: an <img> with its width and height. size (CSS px): 28 and up draws the 3D picture (WebP, 1x and 2x),
 * smaller the Flat one (SVG). label: what it says when it stands alone (else alt="" and aria-hidden: decorative). lazy:
 * below the fold. cls: extra classes. An emoji with no icon comes back as the emoji itself (escaped).
 */
export function iconHtml(e, { size = 20, label = '', lazy = false, cls = '' } = {}) {
  const x = entry(e); if (!x) return esc(e);
  const [name, has3d] = x, big = size >= 28 && has3d;
  const src = big ? `/icons/fluent/3d/${name}-64.webp` : `/icons/fluent/flat/${name}.svg`;
  return `<img class="fx ${big ? 'fx-3d' : 'fx-flat'}${cls ? ` ${esc(cls)}` : ''}" src="${src}"${big ? ` srcset="/icons/fluent/3d/${name}-64.webp 1x, /icons/fluent/3d/${name}-128.webp 2x"` : ''} width="${size}" height="${size}" alt="${esc(label)}"${label ? '' : ' aria-hidden="true"'}${lazy ? ' loading="lazy"' : ''} decoding="async">`;
}
/** Three tools use Fluent's own 3D picture (abacus, mantelpiece clock, coin): WebP like the other 3D icons. */
const TOOL_FLUENT = new Set(['rekenreks', 'clock', 'money']);
/** A manipulatives tool's icon (decorative: the tool's name is next to it). */
export function toolIconHtml(slug, { size = 40, lazy = false } = {}) {
  if (!TOOL_ICONS.includes(slug)) return '';
  const src = TOOL_FLUENT.has(slug) ? `/icons/tools/${slug}-64.webp" srcset="/icons/tools/${slug}-64.webp 1x, /icons/tools/${slug}-128.webp 2x` : `/icons/tools/${slug}.svg`;
  return `<img class="fx fx-3d fx-tool" src="${src}" width="${size}" height="${size}" alt="" aria-hidden="true"${lazy ? ' loading="lazy"' : ''} decoding="async">`;
}
