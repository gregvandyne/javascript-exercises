// Stages one uploaded pack for looking at: node kit2/pipeline/stage-pack.mjs <kit2/packs/pack.json> <raw-dir> <packs-dir> <out-dir> [--all]
// <raw-dir>/<pack>/ is fbx-to-glb.mjs's output, <packs-dir>/<pack>/ the pack as uploaded (for its pictures). Writes the
// optimised models to <out-dir>/<pack>/ with recipe.json (what build-theme.mjs was asked to do) and stage.json (every
// kept model: id, bytes, size, clips; every one left out, with the reason). --all also converts the left-out models
// (into <out-dir>/<pack>/excluded/) so a person can look at them. Nothing here ships: a theme picks from a staged pack
// with its own theme.def.json.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { getBounds } from '@gltf-transform/functions';

const args = process.argv.slice(2), all = args.includes('--all');
const [cfgFile, rawDir, packsDir, outRoot] = args.filter(a => !a.startsWith('--'));
const cfg = JSON.parse(fs.readFileSync(cfgFile, 'utf8'));
const raw = path.join(rawDir, cfg.dir), out = path.join(outRoot, cfg.dir);
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const slug = s => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase();
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
// Pictures by file name, wherever the pack keeps them.
const pics = Object.fromEntries(walk(path.join(packsDir, cfg.dir)).filter(f => /\.(png|jpe?g)$/i.test(f)).map(f => [path.basename(f), path.resolve(f)]));
const why = name => { for (const [k, reason] of Object.entries(cfg.exclude || {})) if (new RegExp(`^(?:${k})$`).test(name)) return reason; return null; };

fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
const recipe = { _: `Staging recipe for ${cfg.name}, generated by kit2/pipeline/stage-pack.mjs.`, texturesDir: '/', models: [] };
const kept = [], excluded = [];
for (const f of fs.readdirSync(raw).filter(f => f.endsWith('.glb')).sort()) {
  const name = f.slice(0, -4), reason = why(name), c = (cfg.creatures || {})[name];
  if (reason) { excluded.push({ name, reason }); if (!all) continue; }
  const doc = await io.read(path.join(raw, f)), root = doc.getRoot();
  const b = getBounds(root.getDefaultScene()), size = b.max.map((v, i) => v - b.min[i]);
  const item = { from: path.join(cfg.dir, f), to: `${reason ? 'excluded/' : c ? 'creatures/' : ''}${(c && c.id) || (cfg.rename || {})[name] || slug(name)}.glb`, ...(cfg.defaults || {}), ...((cfg.items || {})[name] || {}) };
  // A creature (or any item) can ask for a height, length or longest side instead of a scale.
  const to = (c && c.size) || item.size; delete item.size;
  if (to) { const [axis, want] = Object.entries(to)[0]; item.scale = +(want / (axis === 'height' ? size[1] : axis === 'length' ? size[2] : Math.max(...size))).toFixed(4); }
  if (item.textures) item.textures = Object.fromEntries(Object.entries(item.textures).map(([k, v]) => { if (!pics[v]) throw new Error(`${cfg.dir}: no picture ${v}`); return [k, pics[v]]; }));
  const clips = root.listAnimations().map(a => a.getName());
  if (clips.length) {
    // Kid-safe clips only, under plain names: the first clip whose name matches each pattern.
    item.anims = {};
    for (const [as, pattern] of Object.entries({ ...(cfg.clips || {}), ...((c && c.clips) || {}) })) { const hit = pattern && clips.find(n => new RegExp(pattern).test(n)); if (hit) item.anims[as] = hit; }
    item.keepAnims = Object.values(item.anims);   // build-theme.mjs drops every clip not named here, before the renaming
    const used = new Set(Object.values(item.anims));
    item._dropped = [...new Set(clips.filter(n => !used.has(n)).map(n => n.replace(/^.*\|/, '')))].filter(n => ![...used].some(u => u.replace(/^.*\|/, '') === n));
  }
  recipe.models.push(item);
  if (!reason) kept.push({ name, id: path.basename(item.to, '.glb'), file: item.to, ...(c ? { creature: c.name || name } : {}), scale: item.scale || 1, ...(item.anims ? { clips: Object.keys(item.anims), dropped: item._dropped } : {}) });
}
fs.writeFileSync(path.join(out, 'recipe.json'), JSON.stringify(recipe, null, 1) + '\n');
const here = path.dirname(fileURLToPath(import.meta.url));
const r = spawnSync(process.execPath, [path.join(here, 'build-theme.mjs'), path.join(out, 'recipe.json'), rawDir, out, path.join(out, 'sizes.json')], { encoding: 'utf8', maxBuffer: 1 << 28 });
if (r.status !== 0) { console.error(r.stderr); process.exit(1); }
const sizes = JSON.parse(fs.readFileSync(path.join(out, 'sizes.json'), 'utf8')); fs.rmSync(path.join(out, 'sizes.json'));
let bytes = 0;
for (const k of kept) { k.bytes = fs.statSync(path.join(out, k.file)).size; bytes += k.bytes; k.size = sizes[k.file]?.size; k.minY = sizes[k.file]?.minY; }
fs.writeFileSync(path.join(out, 'stage.json'), JSON.stringify({ pack: cfg.dir, name: cfg.name, author: cfg.author, licence: cfg.licence, kept, excluded, bytes }, null, 1) + '\n');
console.log(`${cfg.dir}: kept ${kept.length}, left out ${excluded.length}, ${(bytes / 1048576).toFixed(2)} MB`);
